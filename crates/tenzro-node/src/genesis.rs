    /// The production genesis ships its routes as placeholders: each starts
    /// disabled with zero caps and its placeholder fields recorded, and
    /// opening it is refused, naming the route and the fields, until a vote
    /// installs it whole.
    #[tokio::test]
    async fn production_genesis_installs_placeholder_routes_disabled() {
        use tenzro_types::bridge_route::BridgeRouteMode;
        let g: GenesisConfig =
            toml::from_str(include_str!("../../../config/genesis-prod.toml")).unwrap();
        assert!(!g.economy.bridge_routes.is_empty());
        let dir = tempfile::tempdir().unwrap();
        let store =
            Arc::new(RocksDbStore::open(&StorageConfig::new(dir.path().to_path_buf())).unwrap());
        initialize_genesis(&store, &g).await.unwrap();
        let state = tenzro_vm::StateAdapter::with_storage(
            store.clone() as Arc<dyn tenzro_storage::KvStore>
        );
        for r in &g.economy.bridge_routes {
            let (a, chain) = (r.route.adapter, r.route.source_chain.as_str());
            assert!(!r.placeholders.is_empty() && !r.open);
            assert_eq!(
                tenzro_vm::native::read_bridge_route_mode(&state, a, chain),
                BridgeRouteMode::Disabled
            );
            assert_eq!(
                tenzro_vm::native::read_route_placeholders(&state, a, chain),
                r.placeholders
            );
            let refusal = tenzro_vm::native::bridge_route_open_refusal(&state, a, chain).unwrap();
            assert!(
                refusal.contains(&r.route.storage_key()) && refusal.contains(&r.placeholders[0]),
                "{refusal}"
            );
        }

        // A placeholder route left open, or with caps, or naming a field
        // routes do not have, stops genesis.
        for change in [0, 1, 2] {
            let mut bad = g.clone();
            let r = &mut bad.economy.bridge_routes[0];
            match change {
                0 => r.open = true,
                1 => r.route.mint_limit.per_epoch = 1,
                _ => r.placeholders.push("ramps".into()),
            }
            let dir = tempfile::tempdir().unwrap();
            let store = Arc::new(
                RocksDbStore::open(&StorageConfig::new(dir.path().to_path_buf())).unwrap(),
            );
            assert!(
                initialize_genesis(&store, &bad).await.is_err(),
                "change {change}"
            );
        }
    }

