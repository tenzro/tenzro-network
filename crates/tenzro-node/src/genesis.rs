    /// The digest ignores everything the binary carries and nothing the file
    /// decides.
    #[test]
    fn the_inputs_digest_follows_the_genesis_file_only() {
        let base = chain_compat_genesis(7777, 100);
        let digest = compute_genesis_inputs_digest(&base);
        assert_eq!(digest, compute_genesis_inputs_digest(&base.clone()));
        assert_ne!(
            digest,
            compute_genesis_inputs_digest(&chain_compat_genesis(7778, 100))
        );
        assert_ne!(
            digest,
            compute_genesis_inputs_digest(&chain_compat_genesis(7777, 101))
        );
        let mut named = base.clone();
        named
            .network_params
            .insert(tenzro_vm::native::JAIL_TERM_PARAM.to_string(), 100);
        assert_ne!(digest, compute_genesis_inputs_digest(&named));
        let mut timed = base;
        timed.time.epoch_checkpoints += 1;
        assert_ne!(digest, compute_genesis_inputs_digest(&timed));
    }

