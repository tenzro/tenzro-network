/// ERC-8004 predeploy bundle, baked into the binary at compile time.
///
/// Generated by `tools/predeploys/regenerate.sh`, which spins up a local
/// Anvil node, runs the vendored canonical CREATE2 deploy + UUPS upgrade flow
/// from `vendor/erc8004-evm/` against it, snapshots the resulting state via
/// `anvil_dumpState`, and filters to the 8 addresses Tenzro pre-deploys at
/// block 0: SAFE Singleton Factory + MinimalUUPS + 3 vanity proxies + 3
/// implementation contracts. Schema: `tenzro/erc8004-predeploys/v1`.
///
/// Re-run the regenerate script after bumping the vendor pin to refresh.
const ERC8004_PREDEPLOYS_JSON: &str = include_str!("../res/genesis/erc8004-predeploys.json");

/// Schema string the loader refuses to deserialize anything else under.
const ERC8004_PREDEPLOYS_SCHEMA: &str = "tenzro/erc8004-predeploys/v1";

/// Genesis protocol version for the PQ-hybrid era.
///
/// Under the hybrid PQ migration, every signed transaction carries a mandatory
/// ML-DSA-65 leg alongside the classical Ed25519 signature. Genesis blocks
/// produced by this binary stamp `protocol_version = 2`. A binary that loads
/// a `protocol_version = 1` genesis from storage refuses to start — the older
/// classical-only wire format is not deserializable here, and silently
/// accepting it would mask the incompatibility.
pub const PQ_HYBRID_PROTOCOL_VERSION: u32 = 2;

/// ERC-8004 predeploy bundle (deserialized from `ERC8004_PREDEPLOYS_JSON`).
///
/// `addresses` is a label→hex-address index of the 8 system contracts;
/// `accounts` is the actual on-chain state to install, keyed by the same
/// hex addresses. We use `BTreeMap` so iteration order is deterministic —
/// every validator computes the same genesis state root.
#[derive(Debug, Deserialize)]
struct Erc8004Bundle {
    schema: String,
    source_commit: String,
    addresses: BTreeMap<String, String>,
    accounts: BTreeMap<String, PredeployAccount>,
}

#[derive(Debug, Deserialize)]
struct PredeployAccount {
    nonce: u64,
    /// `"0x<hex>"`, parsed to `u128`. ERC-8004 predeploys all have balance 0,
    /// but the field is honoured so the bundle schema can carry funded
    /// predeploys in future.
    balance: String,
    /// `"0x<hex>"`, raw contract bytecode (not RLP-wrapped, no length prefix).
    code: String,
    /// Slot key (`"0x<32-byte hex>"`) → slot value (`"0x<32-byte hex>"`).
    storage: BTreeMap<String, String>,
}

/// Parse `"0x<hex>"` (or bare `<hex>`) → owned `Vec<u8>`.
fn parse_hex_bytes(s: &str, what: &str) -> Result<Vec<u8>> {
    let stripped = s.strip_prefix("0x").unwrap_or(s);
    hex::decode(stripped)
        .map_err(|e| NodeError::Config(format!("Invalid {} hex {:?}: {}", what, s, e)))
}

/// Parse `"0x<hex>"` into a u128, treating empty/`"0x0"` as zero.
fn parse_hex_u128(s: &str, what: &str) -> Result<u128> {
    let stripped = s.strip_prefix("0x").unwrap_or(s);
    if stripped.is_empty() {
        return Ok(0);
    }
    u128::from_str_radix(stripped, 16)
        .map_err(|e| NodeError::Config(format!("Invalid {} hex u128 {:?}: {}", what, s, e)))
}

/// Right-pad a raw EVM address (20 bytes) to Tenzro's 32-byte address layout
/// by appending 12 zero bytes. This matches `tnzo_balance_key()` in
/// `tenzro_vm::state_adapter` — the canonical CF_ACCOUNTS key for native
/// TNZO balances — so a balance written here is readable by
/// `eth_getBalance`, `tenzro_getBalance`, and revm's `Database::basic()`
/// without any further translation.
fn evm_address_to_tnzo32(evm_addr: &[u8]) -> Result<[u8; 32]> {
    if evm_addr.len() != 20 {
        return Err(NodeError::Config(format!(
            "Expected 20-byte EVM address, got {} bytes",
            evm_addr.len()
        )));
    }
    let mut padded = [0u8; 32];
    padded[..20].copy_from_slice(evm_addr);
    Ok(padded)
}

/// Install the ERC-8004 predeploy bundle into genesis state.
///
/// For each predeploy account, this writes:
/// - `CF_STATE` `code:<40-hex-evm-addr>`     → raw bytecode bytes
/// - `CF_STATE` `nonce:<40-hex-evm-addr>`    → u64 LE (only if `nonce > 0`)
/// - `CF_STATE` `storage:<40-hex>:<64-hex>`  → raw 32-byte slot value
/// - `CF_ACCOUNTS` `balance:<32-byte-padded>` → u128 LE (only if `balance > 0`)
///
/// The key formats are byte-identical to those emitted by
/// `tenzro_vm::state_adapter::StateAdapter::commit()` (and read by
/// `get_code` / `get_storage` / `get_nonce` / `get_balance`), so revm sees
/// these accounts as if they had been deployed by a transaction.
///
/// Returns the SHA-256 commitment of the bundle (incorporated into the
/// genesis state root so validators must agree on the exact predeploy set).
fn install_erc8004_predeploys(
    state_entries: &mut Vec<(Vec<u8>, Vec<u8>)>,
    token_entries: &mut Vec<WriteOp>,
    total_supply: &mut u128,
) -> Result<Hash> {
    let bundle: Erc8004Bundle = serde_json::from_str(ERC8004_PREDEPLOYS_JSON).map_err(|e| {
        NodeError::Config(format!("Failed to parse erc8004-predeploys.json: {}", e))
    })?;

    if bundle.schema != ERC8004_PREDEPLOYS_SCHEMA {
        return Err(NodeError::Config(format!(
            "ERC-8004 predeploy bundle schema mismatch: expected {:?}, got {:?}",
            ERC8004_PREDEPLOYS_SCHEMA, bundle.schema
        )));
    }

    // Cross-check the `addresses` label index against the `accounts` keyspace.
    // The regenerate.sh extractor pairs every label (safeSingletonFactory,
    // minimalUUPS, identityProxy/reputationProxy/validationProxy, identityImpl/
    // reputationImpl/validationImpl) with exactly one account entry — a missing
    // pair means the bundle is corrupt and we refuse to come up rather than
    // silently boot a partially-deployed registry. Comparison is case-
    // insensitive since the bundle uses mixed-case checksummed addresses while
    // `accounts` keys preserve the source casing.
    use std::collections::BTreeSet;
    let account_addrs_lower: BTreeSet<String> = bundle
        .accounts
        .keys()
        .map(|s| s.to_ascii_lowercase())
        .collect();
    for (label, declared_addr) in &bundle.addresses {
        let declared_lower = declared_addr.to_ascii_lowercase();
        if !account_addrs_lower.contains(&declared_lower) {
            return Err(NodeError::Config(format!(
                "ERC-8004 predeploy bundle declares address {} ({}) but no \
                 matching account entry exists — bundle is incoherent",
                declared_addr, label
            )));
        }
    }
    if bundle.addresses.len() != bundle.accounts.len() {
        return Err(NodeError::Config(format!(
            "ERC-8004 predeploy bundle has {} declared addresses but {} \
             account entries — counts must match",
            bundle.addresses.len(),
            bundle.accounts.len()
        )));
    }

    // Commitment is bound to the exact JSON bytes — any drift in the bundle
    // (whether content or whitespace) produces a different genesis root.
    let bundle_commitment = compute_erc8004_bundle_commitment();

    let mut code_count = 0usize;
    let mut storage_slot_count = 0usize;
    let mut funded_count = 0usize;

    for (addr_hex, account) in &bundle.accounts {
        let evm_addr = parse_hex_bytes(addr_hex, "predeploy address")?;
        if evm_addr.len() != 20 {
            return Err(NodeError::Config(format!(
                "ERC-8004 predeploy address {} is {} bytes (expected 20)",
                addr_hex,
                evm_addr.len()
            )));
        }
        // Hex-lowercase the 20-byte address — matches `hex::encode(addr)`
        // in `StateAdapter` getters, which are the readers we must agree with.
        let addr_hex_lower = hex::encode(&evm_addr);

        // --- Code ---
        let code_bytes = parse_hex_bytes(&account.code, "predeploy code")?;
        if code_bytes.is_empty() {
            return Err(NodeError::Config(format!(
                "ERC-8004 predeploy {} has empty code — bundle is corrupt",
                addr_hex
            )));
        }
        let code_key = format!("code:{}", addr_hex_lower);
        state_entries.push((code_key.into_bytes(), code_bytes));
        code_count += 1;

        // --- Nonce (only write if non-zero; absent key reads as 0) ---
        // Canonical home: CF_ACCOUNTS under `b"nonce:" + raw address`, exactly
        // as `StateAdapter::commit()` writes runtime nonce updates, so the state
        // trie sees a single nonce location whether the nonce was set at genesis
        // or by later execution.
        if account.nonce > 0 {
            let raw_addr = parse_hex_bytes(&addr_hex_lower, "predeploy address")?;
            let mut nonce_key = b"nonce:".to_vec();
            nonce_key.extend_from_slice(&raw_addr);
            token_entries.push(WriteOp::Put {
                cf: CF_ACCOUNTS.to_string(),
                key: nonce_key,
                value: account.nonce.to_le_bytes().to_vec(),
            });
        }

        // --- Storage slots ---
        for (slot_key_hex, slot_value_hex) in &account.storage {
            let slot_key = parse_hex_bytes(slot_key_hex, "storage slot key")?;
            let slot_value = parse_hex_bytes(slot_value_hex, "storage slot value")?;
            if slot_key.len() != 32 {
                return Err(NodeError::Config(format!(
                    "Storage slot key {} is {} bytes (expected 32)",
                    slot_key_hex,
                    slot_key.len()
                )));
            }
            // Storage key format mirrors `StateAdapter::get_storage`:
            // `storage:<40-hex-addr>:<64-hex-slot-key>`. Value is the raw
            // 32-byte slot contents.
            let db_key = format!("storage:{}:{}", addr_hex_lower, hex::encode(&slot_key));
            state_entries.push((db_key.into_bytes(), slot_value));
            storage_slot_count += 1;
        }

        // --- Balance (only write if non-zero) ---
        let balance = parse_hex_u128(&account.balance, "predeploy balance")?;
        if balance > 0 {
            let padded = evm_address_to_tnzo32(&evm_addr)?;
            // Single canonical home: CF_ACCOUNTS under tnzo_balance_key layout.
            // No CF_STATE balance mirror — balances are read from CF_ACCOUNTS
            // and the state root is cache-derived.
            let mut token_key = b"balance:".to_vec();
            token_key.extend_from_slice(&padded);
            token_entries.push(WriteOp::Put {
                cf: CF_ACCOUNTS.to_string(),
                key: token_key,
                value: balance.to_le_bytes().to_vec(),
            });
            *total_supply = total_supply.saturating_add(balance);
            funded_count += 1;
        }
    }

    info!(
        "Installed ERC-8004 predeploys: {} contracts, {} storage slots, {} funded, source_commit={}",
        code_count, storage_slot_count, funded_count, bundle.source_commit
    );

    Ok(bundle_commitment)
}

/// Initialize genesis block and state
///
/// This function:
/// 1. Checks if genesis already exists (to support node restarts)
/// 2. Pre-funds configured genesis accounts
/// 3. Creates the genesis block at height 0
/// 4. Persists everything to RocksDB with fsync
pub async fn initialize_genesis(
    store: &Arc<RocksDbStore>,
    genesis_config: &GenesisConfig,
) -> Result<Block> {
    // Check if genesis already exists
    if genesis_exists(store)? {
        info!("Genesis block already exists, loading from storage");
        verify_genesis_matches(store, genesis_config)?;
        return load_genesis_block(store).await;
    }

    // Every state write genesis makes is recorded and committed to the state
    // trie as version 0, the root blocks 1 and 2 carry.
    let writes = tenzro_storage::state_trie::capture::WriteSet::new();
    tenzro_storage::state_trie::capture::in_task(
        writes.clone(),
        create_genesis(store, genesis_config, &writes),
    )
    .await
}

async fn create_genesis(
    store: &Arc<RocksDbStore>,
    genesis_config: &GenesisConfig,
    writes: &Arc<tenzro_storage::state_trie::capture::WriteSet>,
) -> Result<Block> {
    info!(
        "Creating genesis block for chain_id={}",
        genesis_config.chain_id
    );

    // 1. Create account store and pre-fund accounts
    let mut account_store = AccountStoreImpl::new(store.clone());
    let mut state_entries: Vec<(Vec<u8>, Vec<u8>)> = Vec::new();
    // Token balance entries for CF_ACCOUNTS (used by TnzoToken RocksDbBackend)
    let mut token_entries: Vec<WriteOp> = Vec::new();
    let mut total_supply: u128 = 0;

    // Pre-fund genesis accounts
    for ga in &genesis_config.accounts {
        let address = parse_hex_address(&ga.address)?;
        // Multiply whole TNZO units by 10^18 to get smallest unit
        let balance_raw: u128 = ga
            .balance
            .checked_mul(1_000_000_000_000_000_000u128)
            .ok_or_else(|| {
                NodeError::Config(format!("Genesis balance overflow for {}", ga.address))
            })?;

        let account = Account {
            address,
            nonce: Nonce::initial(),
            balance: balance_raw,
            staked: 0,
            state: AccountState::default(),
            storage_root: Hash::zero(),
            code_hash: None,
        };

        account_store
            .put_account(&account)
            .await
            .map_err(|e| NodeError::Other(format!("Failed to store genesis account: {}", e)))?;

        // Single canonical home: CF_ACCOUNTS with the TnzoToken-compatible key
        // format (balance:{raw_bytes}). No CF_STATE balance mirror.
        let mut token_key = b"balance:".to_vec();
        token_key.extend_from_slice(address.as_bytes());
        token_entries.push(WriteOp::Put {
            cf: CF_ACCOUNTS.to_string(),
            key: token_key,
            value: balance_raw.to_le_bytes().to_vec(),
        });
        total_supply = total_supply.saturating_add(balance_raw);

        info!("Pre-funded account {} with {} TNZO", ga.address, ga.balance);
    }

    // Fund the network-rewards pool. Rewards are paid out of this account,
    // never minted, so the genesis supply is the whole supply.
    {
        let pool = tenzro_token::rewards_pool_address();
        let mut token_key = b"balance:".to_vec();
        token_key.extend_from_slice(pool.as_bytes());
        token_entries.push(WriteOp::Put {
            cf: CF_ACCOUNTS.to_string(),
            key: token_key,
            value: tenzro_token::NETWORK_REWARDS_POOL.to_le_bytes().to_vec(),
        });
        total_supply = total_supply
            .checked_add(tenzro_token::NETWORK_REWARDS_POOL)
            .ok_or_else(|| NodeError::Config("Genesis supply overflow".to_string()))?;
    }

    // Install ERC-8004 predeploys (factory + MinimalUUPS + 3 proxies + 3 impls).
    //
    // Must run before the CF_STATE flush so its entries get batched into the
    // same atomic write as the genesis-funded accounts. The returned
    // commitment binds the predeploy bundle into the genesis state root —
    // any drift in `erc8004-predeploys.json` produces a different root,
    // which any honest validator will reject on cross-check.
    let predeploys_commitment =
        install_erc8004_predeploys(&mut state_entries, &mut token_entries, &mut total_supply)?;

    // The network's chain id, which every custody approval is signed for.
    {
        let db_key = format!(
            "storage:{}:{}",
            hex::encode(tenzro_vm::native::SYSTEM_ADDRESS),
            hex::encode(tenzro_vm::native::NETWORK_CHAIN_ID_KEY.as_bytes())
        );
        state_entries.push((
            db_key.into_bytes(),
            genesis_config.chain_id.to_le_bytes().to_vec(),
        ));
    }

    // The chain's protocol version, when the genesis names one. A version
    // this binary cannot execute refuses the genesis outright.
    if let Some(protocol) = genesis_config.protocol {
        tenzro_vm::protocol_range::ProtocolRange::this_binary()
            .check(protocol.version)
            .map_err(|e| NodeError::Config(format!("genesis [protocol]: {e}")))?;
        let db_key = format!(
            "storage:{}:{}",
            hex::encode(tenzro_vm::native::SYSTEM_ADDRESS),
            hex::encode(tenzro_vm::native::PROTOCOL_VERSION_KEY.as_bytes())
        );
        state_entries.push((
            db_key.into_bytes(),
            tenzro_vm::native::genesis_protocol_version(protocol.version)
                .map_err(|e| NodeError::Config(format!("genesis [protocol]: {e}")))?,
        ));
    }

    // The payout schedule, sized to the genesis epoch length so each
    // schedule year spans one calendar year.
    {
        let time = &genesis_config.time;
        let schedule = tenzro_vm::native::genesis_reward_schedule(calendar_epoch_ms(time))
            .map_err(|e| NodeError::Config(format!("genesis [time]: {e}")))?;
        let db_key = format!(
            "storage:{}:{}",
            hex::encode(tenzro_vm::native::SYSTEM_ADDRESS),
            hex::encode(tenzro_vm::native::REWARD_SCHEDULE_KEY.as_bytes())
        );
        state_entries.push((db_key.into_bytes(), schedule));
        if time.calendar_scale > 1 {
            let calendar = tenzro_vm::native::genesis_calendar(
                (genesis_config.timestamp as i64).saturating_mul(1000),
                time.calendar_scale,
            )
            .map_err(|e| NodeError::Config(format!("genesis [time]: {e}")))?;
            let db_key = format!(
                "storage:{}:{}",
                hex::encode(tenzro_vm::native::SYSTEM_ADDRESS),
                hex::encode(tenzro_vm::native::CALENDAR_KEY.as_bytes())
            );
            state_entries.push((db_key.into_bytes(), calendar));
        }
    }

    // Every governed network parameter, so the chain runs on the values in
    // state from the first block.
    genesis_config
        .economy
        .check_tpm_roots()
        .map_err(|e| NodeError::Config(format!("genesis [economy]: {e}")))?;
    genesis_config
        .consensus
        .rules()
        .map_err(|e| NodeError::Config(format!("genesis: {e}")))?;
    let registry_config = genesis_config
        .validator_registry_config()
        .map_err(|e| NodeError::Config(format!("genesis: {e}")))?;
    // The validator registry starts from the genesis's configuration, so no
    // node reads a default its own release compiled in.
    if let Some(cfg) = &registry_config {
        token_entries.push(WriteOp::Put {
            cf: tenzro_storage::CF_TOKENS.to_string(),
            key: tenzro_token::validator_registry::VALIDATOR_CONFIG_KEY
                .as_bytes()
                .to_vec(),
            value: bincode::serialize(cfg)
                .map_err(|e| NodeError::Config(format!("genesis [validator_registry]: {e}")))?,
        });
    }
    for (key, value) in genesis_config
        .network_params()
        .map_err(|e| NodeError::Config(format!("genesis: {e}")))?
    {
        let db_key = format!(
            "storage:{}:{}",
            hex::encode(tenzro_vm::native::SYSTEM_ADDRESS),
            hex::encode(tenzro_vm::native::governed_param_key(key).as_bytes())
        );
        state_entries.push((db_key.into_bytes(), value.to_le_bytes().to_vec()));
    }

    // The TPM manufacturer roots the network starts out recognising;
    // governance replaces them later.
    {
        let db_key = format!(
            "storage:{}:{}",
            hex::encode(tenzro_vm::native::SYSTEM_ADDRESS),
            hex::encode(tenzro_vm::native::ENDORSEMENT_ROOTS_KEY.as_bytes())
        );
        let blob = serde_json::to_vec(&genesis_config.economy.tpm_endorsement_roots_pem)
            .map_err(|e| NodeError::Config(format!("genesis endorsement roots: {e}")))?;
        state_entries.push((db_key.into_bytes(), blob));
    }

    // The network-wide bridge mint limits every route starts bound by;
    // governance replaces them later.
    {
        let limits = genesis_config
            .economy
            .bridge_mint_limits()
            .map_err(NodeError::Config)?;
        let db_key = format!(
            "storage:{}:{}",
            hex::encode(tenzro_vm::native::SYSTEM_ADDRESS),
            hex::encode(tenzro_vm::native::BRIDGE_MINT_LIMITS_KEY.as_bytes())
        );
        let blob = serde_json::to_vec(&limits)
            .map_err(|e| NodeError::Config(format!("genesis bridge mint limits: {e}")))?;
        state_entries.push((db_key.into_bytes(), blob));
    }

    // The network-wide outflow caps: the most of each unit that may leave
    // over every route together in one epoch; governance replaces them later.
    {
        let limits = genesis_config
            .economy
            .bridge_outflow_limits()
            .map_err(NodeError::Config)?;
        let db_key = format!(
            "storage:{}:{}",
            hex::encode(tenzro_vm::native::SYSTEM_ADDRESS),
            hex::encode(tenzro_vm::native::BRIDGE_OUTFLOW_LIMITS_KEY.as_bytes())
        );
        let blob = serde_json::to_vec(&limits)
            .map_err(|e| NodeError::Config(format!("genesis bridge outflow limits: {e}")))?;
        state_entries.push((db_key.into_bytes(), blob));
    }

    // The chains agents hold accounts on.
    {
        let system = hex::encode(tenzro_vm::native::SYSTEM_ADDRESS);
        let mut seen = std::collections::HashSet::new();
        for c in &genesis_config.economy.agent_account_chains {
            c.validate().map_err(|e| {
                NodeError::Config(format!("genesis agent account chain {}: {e}", c.caip2))
            })?;
            if !seen.insert(c.caip2.clone()) {
                return Err(NodeError::Config(format!(
                    "genesis lists agent account chain {} twice",
                    c.caip2
                )));
            }
            let key = tenzro_types::omni_account::AgentAccountChain::storage_key(&c.caip2);
            let blob = serde_json::to_vec(c).map_err(|e| {
                NodeError::Config(format!("genesis agent account chain {}: {e}", c.caip2))
            })?;
            state_entries.push((
                format!("storage:{system}:{}", hex::encode(key.as_bytes())).into_bytes(),
                blob,
            ));
        }
        // The chain index the treasury's accounts are listed from.
        if !seen.is_empty() {
            let mut chains: Vec<String> = seen.into_iter().collect();
            chains.sort();
            let key = tenzro_vm::native::treasury_remote::CHAIN_INDEX_KEY;
            let blob = serde_json::to_vec(&chains)
                .map_err(|e| NodeError::Config(format!("genesis chain index: {e}")))?;
            state_entries.push((
                format!("storage:{system}:{}", hex::encode(key.as_bytes())).into_bytes(),
                blob,
            ));
        }
    }

    // The guardian seats the network starts with, each a hard expiry within
    // the governed maximum term of the genesis time. Placeholder seats are
    // not written: governance fills them.
    {
        let system = hex::encode(tenzro_vm::native::SYSTEM_ADDRESS);
        let genesis_ms = (genesis_config.timestamp as i64).saturating_mul(1000);
        let mut seen = std::collections::HashSet::new();
        let mut roots = std::collections::HashSet::new();
        let mut index: Vec<String> = Vec::new();
        let mut stewards = 0u64;
        for g in &genesis_config.economy.guardians {
            if g.placeholder {
                warn!(
                    role = g.role.as_str(),
                    "genesis guardian seat is a placeholder; governance fills it"
                );
                continue;
            }
            if genesis_ms == 0 {
                return Err(NodeError::Config(
                    "a genesis that seats guardians fixes its timestamp".to_string(),
                ));
            }
            tenzro_vm::governance::check_guardian_term(
                &g.did,
                g.term_ends_ms,
                genesis_ms,
                tenzro_vm::governance::DEFAULT_GUARDIAN_MAX_TERM_MS,
            )
            .map_err(|e| NodeError::Config(format!("genesis guardian {}: {e}", g.did)))?;
            let address = parse_hex_bytes(&g.address, "genesis guardian address")?;
            if !seen.insert(address.clone()) {
                return Err(NodeError::Config(format!(
                    "genesis seats guardian {} twice",
                    g.address
                )));
            }
            let key_root = g.key_root.clone().ok_or_else(|| {
                NodeError::Config(format!("genesis guardian {} names no key root", g.did))
            })?;
            key_root
                .validate()
                .map_err(|e| NodeError::Config(format!("genesis guardian {}: {e}", g.did)))?;
            if !roots.insert((g.role, key_root.clone())) {
                return Err(NodeError::Config(format!(
                    "genesis seats two {} guardians on one key root",
                    g.role.as_str()
                )));
            }
            if g.role == tenzro_vm::governance::GuardianRole::Steward {
                if g.term_ends_ms as u64
                    > genesis_config.network_param(tenzro_vm::governance::STEWARD_SUNSET_PARAM)
                {
                    return Err(NodeError::Config(format!(
                        "genesis steward {} outlasts the stewardship sunset",
                        g.did
                    )));
                }
                stewards += 1;
                if stewards
                    > genesis_config.network_param(tenzro_vm::governance::STEWARD_MAX_SEATS_PARAM)
                {
                    return Err(NodeError::Config(
                        "genesis seats more stewards than the cap".to_string(),
                    ));
                }
            }
            let seat = tenzro_vm::governance::GuardianSeat {
                did: g.did.clone(),
                role: g.role,
                term_ends_ms: g.term_ends_ms,
                key_root,
            };
            let key = tenzro_vm::native::guardian::seat_key(&address);
            let blob = serde_json::to_vec(&seat)
                .map_err(|e| NodeError::Config(format!("genesis guardian {}: {e}", g.did)))?;
            state_entries.push((
                format!("storage:{system}:{}", hex::encode(key.as_bytes())).into_bytes(),
                blob,
            ));
            index = tenzro_vm::native::guardian::index_with(index, &address, true);
        }
        if !index.is_empty() {
            let key = tenzro_vm::native::guardian::INDEX_KEY;
            let blob = serde_json::to_vec(&index)
                .map_err(|e| NodeError::Config(format!("genesis guardian index: {e}")))?;
            state_entries.push((
                format!("storage:{system}:{}", hex::encode(key.as_bytes())).into_bytes(),
                blob,
            ));
        }
    }

    // The bridge routes the network starts with. A filled route is held to
    // the rules a proposed route is held to, and its committees are drawn on
    // chain from the genesis time, as after an enacted proposal; a placeholder route is installed as written, with its
    // placeholder fields recorded, so a governance vote can fill it and
    // another open it. A closed route starts disabled by governance.
    {
        let system = hex::encode(tenzro_vm::native::SYSTEM_ADDRESS);
        let entry = |key: String, blob: Vec<u8>| {
            (
                format!("storage:{system}:{}", hex::encode(key.as_bytes())).into_bytes(),
                blob,
            )
        };
        let mut seen = std::collections::HashSet::new();
        for g in &genesis_config.economy.bridge_routes {
            let key = g.route.storage_key();
            g.check_placeholders().map_err(NodeError::Config)?;
            if g.placeholders.is_empty() {
                g.route
                    .validate_proposal()
                    .map_err(|e| NodeError::Config(format!("genesis bridge route {key}: {e}")))?;
            }
            if !seen.insert(key.clone()) {
                return Err(NodeError::Config(format!(
                    "genesis lists bridge route {key} twice"
                )));
            }
            let fail = |e: serde_json::Error| {
                NodeError::Config(format!("genesis bridge route {key}: {e}"))
            };
            state_entries.push(entry(
                key.clone(),
                serde_json::to_vec(&g.route).map_err(fail)?,
            ));
            if g.placeholders.is_empty() {
                let (term, blob) = tenzro_vm::native::bridge_committee::genesis_term_entry(
                    &g.route,
                    (genesis_config.timestamp as i64).saturating_mul(1000),
                )
                .map_err(|e| NodeError::Config(format!("genesis bridge route {key}: {e}")))?;
                state_entries.push(entry(term, blob));
            }
            if !g.placeholders.is_empty() {
                let placeholders = tenzro_vm::native::bridge_placeholders_key(
                    g.route.adapter,
                    &g.route.source_chain,
                );
                state_entries.push(entry(
                    placeholders,
                    serde_json::to_vec(&g.placeholders).map_err(fail)?,
                ));
            }
            if !g.open {
                let trip = tenzro_vm::native::BridgeCircuitTrip {
                    adapter: g.route.adapter,
                    source_chain: g.route.source_chain.clone(),
                    mode: tenzro_types::bridge_route::BridgeRouteMode::Disabled,
                    by: tenzro_vm::native::BridgeCircuitAuthority::Governance,
                    reason: "closed at genesis; an enacted policy update opens it".to_string(),
                    evidence_hash: None,
                    epoch: 0,
                    at_ms: (genesis_config.timestamp as i64).saturating_mul(1000),
                };
                let circuit =
                    tenzro_vm::native::bridge_circuit_key(g.route.adapter, &g.route.source_chain);
                state_entries.push(entry(circuit, serde_json::to_vec(&trip).map_err(fail)?));
            }
        }
        // The routes with a settlement lock, which the chain opens a
        // reconciliation task for each epoch.
        let locked: Vec<(tenzro_types::bridge_route::BridgeRouteAdapter, String)> = genesis_config
            .economy
            .bridge_routes
            .iter()
            .filter(|g| g.route.settlement_lock.is_some())
            .map(|g| (g.route.adapter, g.route.source_chain.clone()))
            .collect();
        if !locked.is_empty() {
            let blob = serde_json::to_vec(&locked)
                .map_err(|e| NodeError::Config(format!("genesis reconciliation routes: {e}")))?;
            state_entries.push(entry(tenzro_vm::native::RECON_ROUTES_KEY.to_string(), blob));
        }
    }

    // The finality program whose wrapped proofs the chain accepts, when the
    // genesis names one; governance sets or replaces it later.
    if let Some(program) = &genesis_config.economy.finality_program {
        let image_id: [u8; 32] = hex::decode(program.trim_start_matches("0x"))
            .ok()
            .and_then(|b| b.try_into().ok())
            .ok_or_else(|| {
                NodeError::Config("finality_program must be a 32-byte hex image id".into())
            })?;
        let db_key = format!(
            "storage:{}:{}",
            hex::encode(tenzro_vm::native::SYSTEM_ADDRESS),
            hex::encode(tenzro_vm::native::FINALITY_PROGRAM_KEY.as_bytes())
        );
        let blob = serde_json::to_vec(&hex::encode(image_id))
            .map_err(|e| NodeError::Config(format!("genesis finality program: {e}")))?;
        state_entries.push((db_key.into_bytes(), blob));
    }
    // The handover program whose chain proofs nodes accept, when the genesis
    // names one; governance sets or replaces it later.
    if let Some(program) = &genesis_config.economy.handover_program {
        let image_id: [u8; 32] = hex::decode(program.trim_start_matches("0x"))
            .ok()
            .and_then(|b| b.try_into().ok())
            .ok_or_else(|| {
                NodeError::Config("handover_program must be a 32-byte hex image id".into())
            })?;
        let db_key = format!(
            "storage:{}:{}",
            hex::encode(tenzro_vm::native::SYSTEM_ADDRESS),
            hex::encode(tenzro_vm::native::HANDOVER_PROGRAM_KEY.as_bytes())
        );
        let blob = serde_json::to_vec(&hex::encode(image_id))
            .map_err(|e| NodeError::Config(format!("genesis handover program: {e}")))?;
        state_entries.push((db_key.into_bytes(), blob));
    }

    // Each genesis validator's stake is bonded in the staking vault, and its
    // consensus key indexed to its account, so the chain slashes a genesis
    // validator by the same rule as one that registered later.
    {
        let mut bonds = Vec::with_capacity(genesis_config.validators.len());
        for v in &genesis_config.validators {
            let (info, vrf_key) = v.decode_with_vrf_key()?;
            let amount = (v.stake as u128)
                .checked_mul(1_000_000_000_000_000_000u128)
                .ok_or_else(|| {
                    NodeError::Config(format!("Genesis stake overflow for {}", v.address))
                })?;
            bonds.push((
                info.address.0,
                info.public_key.fingerprint(),
                vrf_key,
                amount,
            ));
        }
        let (mut entries, bonded) = tenzro_vm::native::genesis_validator_bonds(&bonds)
            .map_err(|e| NodeError::Config(format!("genesis validators: {e}")))?;
        // The genesis validators are the admitted set while validator
        // admission is closed (validator.admission_approval, set by the
        // genesis file): each one is written as approved.
        let admitted: Vec<[u8; 32]> = bonds.iter().map(|b| b.0).collect();
        entries.extend(tenzro_vm::validator_admission::genesis_entries(&admitted));
        if bonded > 0 {
            let system = hex::encode(tenzro_vm::native::SYSTEM_ADDRESS);
            for (key, value) in entries {
                state_entries.push((
                    format!("storage:{system}:{}", hex::encode(&key)).into_bytes(),
                    value,
                ));
            }
            token_entries.push(WriteOp::Put {
                cf: CF_ACCOUNTS.to_string(),
                key: tenzro_vm::state_adapter::tnzo_balance_key(
                    &tenzro_vm::native::staking_vault_address(),
                ),
                value: bonded.to_le_bytes().to_vec(),
            });
            total_supply = total_supply
                .checked_add(bonded)
                .ok_or_else(|| NodeError::Config("Genesis supply overflow".to_string()))?;
        }
    }

    // Role stakes for the non-validator roles are bonded in the role-stake
    // vault, so a bootstrap node serving them boots on the genesis alone.
    {
        let bonds = genesis_config
            .role_stakes
            .iter()
            .map(|r| r.decode(&genesis_config.stake_ladder()))
            .collect::<Result<Vec<_>>>()?;
        let (entries, bonded) = tenzro_vm::native::genesis_role_bonds(&bonds)
            .map_err(|e| NodeError::Config(format!("genesis role stakes: {e}")))?;
        if bonded > 0 {
            let system = hex::encode(tenzro_vm::native::SYSTEM_ADDRESS);
            for (key, value) in entries {
                state_entries.push((
                    format!("storage:{system}:{}", hex::encode(&key)).into_bytes(),
                    value,
                ));
            }
            token_entries.push(WriteOp::Put {
                cf: CF_ACCOUNTS.to_string(),
                key: tenzro_vm::state_adapter::tnzo_balance_key(
                    tenzro_vm::native::role_stake_vault().as_bytes(),
                ),
                value: bonded.to_le_bytes().to_vec(),
            });
            total_supply = total_supply
                .checked_add(bonded)
                .ok_or_else(|| NodeError::Config("Genesis supply overflow".to_string()))?;
        }
    }

    // Genesis never creates more than the fixed supply.
    tenzro_token::tnzo::check_genesis_supply(total_supply)
        .map_err(|e| NodeError::Config(e.to_string()))?;

    // Write state entries to CF_STATE
    if !state_entries.is_empty() {
        let ops: Vec<WriteOp> = state_entries
            .into_iter()
            .map(|(k, v)| WriteOp::Put {
                cf: CF_STATE.to_string(),
                key: k,
                value: v,
            })
            .collect();
        store
            .write_batch(ops)
            .map_err(|e| NodeError::Other(format!("Failed to write genesis state: {}", e)))?;
    }

    // Write token balances to CF_ACCOUNTS (used by TnzoToken::balance_of via RocksDbBackend)
    if !token_entries.is_empty() {
        // Also store total supply
        token_entries.push(WriteOp::Put {
            cf: CF_ACCOUNTS.to_string(),
            key: b"total_supply".to_vec(),
            value: total_supply.to_le_bytes().to_vec(),
        });
        store.write_batch(token_entries).map_err(|e| {
            NodeError::Other(format!("Failed to write genesis token balances: {}", e))
        })?;
        info!(
            "Genesis token balances written to CF_ACCOUNTS (total supply: {} wei)",
            total_supply
        );
    }

    // 2. Compute state root (simplified - hash of all accounts + predeploy commitment)
    let state_root = compute_genesis_state_root(genesis_config, &predeploys_commitment);

    // 3. Create genesis block
    // Taken from the configuration only, never from the local clock: the
    // genesis block's hash is what block 1 links to, so every node must derive
    // the same one. A configuration without a timestamp gives zero.
    let timestamp = Timestamp::new(genesis_config.timestamp as i64 * 1000);

    let genesis_block = Block {
        header: BlockHeader {
            height: BlockHeight::genesis(),
            epoch: 0,
            round: 0,
            anchor: Hash::zero(),
            prev_hash: Hash::zero(),
            tx_root: Hash::zero(),
            state_root,
            event_root: tenzro_types::chain_event::event_root(&[]),
            receipts_root: Hash::new(tenzro_types::eth_receipt::EMPTY_TRIE_ROOT),
            logs_bloom: tenzro_types::LogsBloom::default(),
            timestamp,
            proposer: Address::zero(), // Genesis has no proposer
            metadata: BlockMetadata {
                gas_used: 0,
                gas_limit: 0,
                tx_count: 0,
                protocol_version: genesis_config
                    .protocol
                    .map_or(PQ_HYBRID_PROTOCOL_VERSION, |p| p.version),
                // EIP-1559 base fee at genesis (1 Gwei). Every later block
                // stamps the base fee its execution charges.
                base_fee_per_gas: Some(
                    tenzro_types::block::FeeMarketParams::default().initial_base_fee,
                ),
            },
        },
        transactions: Vec::new(),
    };

    // 4. Persist genesis block
    let mut block_store = BlockStoreImpl::new(store.clone())
        .map_err(|e| NodeError::Other(format!("Failed to create block store: {}", e)))?;

    block_store
        .put_block(&genesis_block)
        .await
        .map_err(|e| NodeError::Other(format!("Failed to store genesis block: {}", e)))?;

    // 5. Commit the genesis state as state-trie version 0, before the marker
    //    below: a node that stops in between recreates genesis on restart
    //    rather than running without a committed root.
    let genesis_root = tenzro_storage::StateTrie::new(store.clone() as Arc<dyn KvStore>)
        .commit(0, &writes.take())
        .map_err(|e| NodeError::Other(format!("Failed to commit genesis state: {}", e)))?;
    info!(root = %genesis_root, "Genesis state committed");

    // 6. Mark genesis as initialized
    store
        .put(CF_METADATA, b"genesis_initialized", b"true")
        .map_err(|e| NodeError::Other(format!("Failed to mark genesis: {}", e)))?;

    // Store chain_id
    store
        .put(
            CF_METADATA,
            b"chain_id",
            &genesis_config.chain_id.to_le_bytes(),
        )
        .map_err(|e| NodeError::Other(format!("Failed to store chain_id: {}", e)))?;

    // Persist the genesis state_root so a restart-time chain-compat check
    // (`verify_genesis_matches`) can refuse to start when the configured
    // genesis no longer matches the on-disk chain. Without this the only
    // way to detect "wrong genesis vs. existing DB" is by waiting for
    // consensus to diverge from peers — silent corruption of the
    // validator's local state until the operator notices. The state_root
    // already binds chain_id, accounts, and the ERC-8004 predeploy
    // bundle (see `compute_genesis_state_root`), so a single 32-byte
    // value is sufficient to detect any genesis drift.
    store
        .put(CF_METADATA, b"genesis_state_root", state_root.as_bytes())
        .map_err(|e| NodeError::Other(format!("Failed to store genesis_state_root: {}", e)))?;

    // The restart check compares this, not the state root: it covers what the
    // operator's genesis file decides and nothing the binary carries, so a
    // release that adds a governed key or edits the predeploy bundle starts
    // on the data directory it finds.
    store
        .put(
            CF_METADATA,
            b"genesis_inputs_digest",
            compute_genesis_inputs_digest(genesis_config).as_bytes(),
        )
        .map_err(|e| NodeError::Other(format!("Failed to store genesis_inputs_digest: {}", e)))?;

    info!(
        "Genesis block created at height 0, state_root={}",
        state_root
    );

    Ok(genesis_block)
}

/// Compute the SHA-256 commitment of the embedded ERC-8004 predeploy bundle.
///
/// The same commitment is folded into the genesis state_root (so validators
/// must agree on the exact predeploy set) and is referenced by
/// `verify_genesis_matches` to detect binary-level genesis drift on restart.
fn compute_erc8004_bundle_commitment() -> Hash {
    use sha2::{Digest, Sha256};
    let mut h = Sha256::new();
    h.update(b"tenzro/erc8004-predeploys");
    h.update(ERC8004_PREDEPLOYS_JSON.as_bytes());
    let digest = h.finalize();
    Hash::from_bytes(digest.as_slice()).expect("SHA-256 always produces 32 bytes")
}

/// Cross-check the configured genesis against what's already persisted on
/// disk. Refuse to start when the genesis file the node is given is not the
/// one the data directory was created from.
///
/// - **chain_id drift**: hard error. The operator pointed the binary at the
///   wrong genesis file or a different network's data directory. The operator
///   must either fix the genesis path or intentionally wipe the data
///   directory.
/// - **`genesis_inputs_digest` drift** (the genesis file was edited: accounts,
///   time rules, role stakes, parameter values, TPM roots, bridge routes,
///   guardians): hard error, same remedy.
/// - **No `genesis_inputs_digest` stored**: hard error. Initialisation always
///   writes it; a data directory without it was not created by this network's
///   software.
///
/// What the binary carries is not compared. The predeploy bundle, the list of
/// governed parameters and their compiled defaults are already in the state
/// the data directory holds; a binary whose execution differs is caught by the
/// state root of the first block it disagrees on, not by refusing to start. The
/// stored `genesis_state_root` is kept for the pin test and for operators; a
/// difference from the recomputed root is logged and is not an error.
///
/// Errors are surfaced as `NodeError::Config` so the operator gets a
/// clean abort with an actionable message rather than a panic.
fn verify_genesis_matches(store: &Arc<RocksDbStore>, genesis_config: &GenesisConfig) -> Result<()> {
    // 1. chain_id check
    let stored_chain_id_bytes = store
        .get(CF_METADATA, b"chain_id")
        .map_err(|e| NodeError::Other(format!("Failed to read stored chain_id: {}", e)))?;
    if let Some(bytes) = stored_chain_id_bytes {
        if bytes.len() != 8 {
            return Err(NodeError::Other(format!(
                "Stored chain_id has wrong length: expected 8 bytes (u64 LE), got {}. \
                 Storage may be corrupt — investigate before retrying.",
                bytes.len()
            )));
        }
        let mut chain_id_arr = [0u8; 8];
        chain_id_arr.copy_from_slice(&bytes);
        let stored_chain_id = u64::from_le_bytes(chain_id_arr);
        if stored_chain_id != genesis_config.chain_id {
            return Err(NodeError::Config(format!(
                "Chain incompatibility detected: configured genesis chain_id={} but \
                 on-disk chain has chain_id={}. This binary will not start against \
                 a foreign chain's state. Either (a) point --genesis at the correct \
                 genesis.toml for chain_id={}, or (b) intentionally wipe the data \
                 directory (rm -rf <data-dir>/db <data-dir>/snapshots \
                 <data-dir>/consensus) to bootstrap a fresh chain.",
                genesis_config.chain_id, stored_chain_id, stored_chain_id
            )));
        }
    } else {
        // chain_id missing while genesis_initialized is true — back-fill so
        // future checks have something to compare against. Storage is from
        // a pre-fix binary; the on-disk chain is whatever the binary
        // assumes. We accept it; the state_root check below will still
        // catch drift in the binary's genesis assembly.
        store
            .put(
                CF_METADATA,
                b"chain_id",
                &genesis_config.chain_id.to_le_bytes(),
            )
            .map_err(|e| NodeError::Other(format!("Failed to back-fill chain_id: {}", e)))?;
        info!(
            "Back-filled chain_id={} into CF_METADATA (pre-fix upgrade path)",
            genesis_config.chain_id
        );
    }

    // 2. genesis_inputs_digest check
    let configured_digest = compute_genesis_inputs_digest(genesis_config);
    let stored_digest = store
        .get(CF_METADATA, b"genesis_inputs_digest")
        .map_err(|e| {
            NodeError::Other(format!(
                "Failed to read stored genesis_inputs_digest: {}",
                e
            ))
        })?
        .ok_or_else(|| {
            NodeError::Config(
                "The data directory has no genesis_inputs_digest, so it was not created by this \
                 network's software. Refusing to start. Intentionally wipe the data directory \
                 (rm -rf <data-dir>/db <data-dir>/snapshots <data-dir>/consensus) to \
                 bootstrap a fresh chain."
                    .to_string(),
            )
        })?;
    if stored_digest.as_slice() != configured_digest.as_bytes() {
        return Err(NodeError::Config(format!(
            "Genesis inputs mismatch: the configured genesis file hashes to {} but the \
             on-disk chain was created from {}. The genesis file was edited (different \
             accounts, time rules, role stakes, parameters, roots, routes or guardians). \
             Refusing to start to prevent silent state corruption. Resolve by (a) reverting \
             the genesis change, or (b) intentionally wiping the data directory to bootstrap a \
             fresh chain.",
            configured_digest,
            hex::encode(&stored_digest)
        )));
    }

    // The state root also covers what the binary carries. A difference means
    // this binary carries other inputs than the one that created the chain,
    // which is what a governed upgrade is; it is not a mismatch.
    let configured_root =
        compute_genesis_state_root(genesis_config, &compute_erc8004_bundle_commitment());
    match store.get(CF_METADATA, b"genesis_state_root") {
        Ok(Some(root)) if root.as_slice() != configured_root.as_bytes() => info!(
            "This binary's genesis state root {} differs from the stored {}: it carries other \
             genesis inputs than the binary that created the chain. Continuing.",
            configured_root,
            hex::encode(root)
        ),
        _ => {}
    }
    info!(
        "Chain compatibility verified: chain_id={} genesis_inputs_digest={}",
        genesis_config.chain_id, configured_digest
    );

    Ok(())
}

/// Check if genesis block has already been initialized
fn genesis_exists(store: &Arc<RocksDbStore>) -> Result<bool> {
    match store.get(CF_METADATA, b"genesis_initialized") {
        Ok(Some(_)) => Ok(true),
        Ok(None) => Ok(false),
        Err(e) => Err(NodeError::Other(format!("Failed to check genesis: {}", e))),
    }
}

/// Load existing genesis block from storage
async fn load_genesis_block(store: &Arc<RocksDbStore>) -> Result<Block> {
    let block_store = BlockStoreImpl::new(store.clone())
        .map_err(|e| NodeError::Other(format!("Failed to create block store: {}", e)))?;

    let genesis = block_store
        .get_block_by_height(BlockHeight::genesis())
        .await
        .map_err(|e| NodeError::Other(format!("Failed to load genesis block: {}", e)))?
        .ok_or_else(|| NodeError::Other("Genesis block not found in storage".to_string()))?;

    // Refuse to start on a pre-PQ genesis. The classical-only wire format from
    // protocol_version=1 is not deserializable by this binary; bringing it up
    // would silently accept a chain whose transaction format we cannot replay.
    let stored_version = genesis.header.metadata.protocol_version;
    if stored_version < PQ_HYBRID_PROTOCOL_VERSION {
        return Err(NodeError::Other(format!(
            "Refusing to start: stored genesis declares protocol_version={} but \
             this binary requires protocol_version={} (PQ-hybrid era). The older \
             classical-only transaction format is no longer supported. Wipe the \
             data directory to re-bootstrap from genesis.",
            stored_version, PQ_HYBRID_PROTOCOL_VERSION
        )));
    }

    info!(
        "Loaded existing genesis block from storage (protocol_version={})",
        stored_version
    );
    Ok(genesis)
}

/// Parse hex-encoded address (with or without 0x prefix)
fn parse_hex_address(hex_str: &str) -> Result<Address> {
    let hex_clean = hex_str.strip_prefix("0x").unwrap_or(hex_str);
    let bytes = hex::decode(hex_clean)
        .map_err(|e| NodeError::Config(format!("Invalid hex address '{}': {}", hex_str, e)))?;

    if bytes.len() > 32 {
        return Err(NodeError::Config(format!(
            "Address too long: {} bytes (max 32)",
            bytes.len()
        )));
    }

    let mut addr_bytes = [0u8; 32];
    let len = bytes.len().min(32);
    addr_bytes[..len].copy_from_slice(&bytes[..len]);

    Ok(Address::new(addr_bytes))
}

/// Compute the genesis state root from the configuration.
///
/// The genesis root is a deterministic SHA-256 commitment over the genesis
/// configuration (chain id, funded accounts) plus the
/// ERC-8004 predeploy bundle commitment — intentionally NOT a Merkle
/// Patricia Trie root. Genesis state is injected into the state trie
/// separately at boot; this value only needs to be identical across every
/// validator loading the same configuration, and it is baked into the live
/// genesis, so its preimage layout must never change. Binding
/// `predeploys_commitment` here means any drift in
/// `erc8004-predeploys.json` (bytecode, slot values, the set of addresses)
/// produces a different genesis root, so a peer with a stale bundle will
/// fail header verification.
/// SHA-256 over what the operator's genesis file decides and nothing the
/// binary carries: the chain id, accounts, time rules, role stakes as written,
/// the parameter values the file names, TPM roots, agent account chains,
/// bridge routes and guardians. Stored at creation and compared on restart.
fn compute_genesis_inputs_digest(genesis: &GenesisConfig) -> Hash {
    use sha2::{Digest, Sha256};

    fn field(h: &mut Sha256, bytes: &[u8]) {
        h.update((bytes.len() as u64).to_le_bytes());
        h.update(bytes);
    }

    let mut h = Sha256::new();
    h.update(b"tenzro_genesis_inputs_v1");
    h.update(genesis.chain_id.to_le_bytes());
    for account in &genesis.accounts {
        field(&mut h, account.address.as_bytes());
        h.update(account.balance.to_le_bytes());
    }
    h.update(genesis.time.digest());
    for r in &genesis.role_stakes {
        field(&mut h, &serde_json::to_vec(r).unwrap_or_default());
    }
    for (key, value) in &genesis.network_params {
        field(&mut h, key.as_bytes());
        h.update(value.to_le_bytes());
    }
    for pem in &genesis.economy.tpm_endorsement_roots_pem {
        field(&mut h, pem.as_bytes());
    }
    for c in &genesis.economy.agent_account_chains {
        field(&mut h, &serde_json::to_vec(c).unwrap_or_default());
    }
    for g in &genesis.economy.bridge_routes {
        field(&mut h, &serde_json::to_vec(&g.route).unwrap_or_default());
        h.update([u8::from(g.open)]);
    }
    for g in &genesis.economy.guardians {
        field(&mut h, &serde_json::to_vec(g).unwrap_or_default());
    }
    // Committed only when named, so a genesis without `[protocol]` keeps the
    // digest it always had.
    if let Some(p) = &genesis.protocol {
        field(&mut h, b"protocol_version");
        h.update(p.version.to_le_bytes());
    }
    // The ordering rules, committed only when the genesis names one.
    if genesis.consensus.is_named() {
        field(&mut h, b"consensus");
        field(
            &mut h,
            &serde_json::to_vec(&genesis.consensus).unwrap_or_default(),
        );
    }
    if genesis.validator_registry.is_named() {
        field(&mut h, b"validator_registry");
        field(
            &mut h,
            &serde_json::to_vec(&genesis.validator_registry).unwrap_or_default(),
        );
    }
    Hash::from_bytes(h.finalize().as_slice()).expect("SHA-256 always produces 32 bytes")
}

fn compute_genesis_state_root(genesis: &GenesisConfig, predeploys_commitment: &Hash) -> Hash {
    use sha2::{Digest, Sha256};

    let mut hasher = Sha256::new();
    hasher.update(b"tenzro_genesis_v1");
    hasher.update(genesis.chain_id.to_le_bytes());

    // Hash all genesis accounts
    for account in &genesis.accounts {
        hasher.update(account.address.as_bytes());
        hasher.update(account.balance.to_le_bytes());
    }

    // Bind ERC-8004 predeploy bundle into the root.
    hasher.update(predeploys_commitment.as_bytes());

    // Bind the time rules: nodes running different ones get different
    // genesis blocks.
    hasher.update(genesis.time.digest());

    // Bind the genesis role stakes.
    let ladder = genesis.stake_ladder();
    for r in &genesis.role_stakes {
        hasher.update(b"role_stake");
        hasher.update(
            r.address
                .to_ascii_lowercase()
                .trim_start_matches("0x")
                .as_bytes(),
        );
        hasher.update(r.role.as_bytes());
        // The amount bonded, whether named or taken from the governed ladder.
        let amount = r.decode(&ladder).map(|b| b.amount).unwrap_or_default();
        hasher.update(amount.to_le_bytes());
        hasher.update(serde_json::to_vec(&r.capacity).unwrap_or_default());
    }

    // Bind the governed network parameters.
    if let Ok(params) = genesis.network_params() {
        for (key, value) in params {
            hasher.update(key.as_bytes());
            hasher.update(value.to_le_bytes());
        }
    }
    for pem in &genesis.economy.tpm_endorsement_roots_pem {
        hasher.update((pem.len() as u64).to_le_bytes());
        hasher.update(pem.as_bytes());
    }

    // Bind the agent account chains.
    for c in &genesis.economy.agent_account_chains {
        let chain = serde_json::to_vec(c).unwrap_or_default();
        hasher.update((chain.len() as u64).to_le_bytes());
        hasher.update(&chain);
    }

    // Bind the bridge routes and whether each starts open.
    for g in &genesis.economy.bridge_routes {
        let route = serde_json::to_vec(&g.route).unwrap_or_default();
        hasher.update((route.len() as u64).to_le_bytes());
        hasher.update(&route);
        hasher.update([u8::from(g.open)]);
    }

    // Bind the guardian seats.
    for g in &genesis.economy.guardians {
        let seat = serde_json::to_vec(g).unwrap_or_default();
        hasher.update((seat.len() as u64).to_le_bytes());
        hasher.update(&seat);
    }

    // Bind the protocol version, only when the genesis names one, so a
    // genesis without `[protocol]` keeps the root it always had.
    if let Some(p) = &genesis.protocol {
        hasher.update(b"protocol_version");
        hasher.update(p.version.to_le_bytes());
    }

    // Bind the ordering rules, only when the genesis names one, so a genesis
    // without `[consensus]` keeps the root it always had.
    if genesis.consensus.is_named() {
        let rules = serde_json::to_vec(&genesis.consensus).unwrap_or_default();
        hasher.update(b"consensus");
        hasher.update((rules.len() as u64).to_le_bytes());
        hasher.update(&rules);
    }
    // Bind the validator registry rules, only when the genesis names them.
    if genesis.validator_registry.is_named() {
        let rules = serde_json::to_vec(&genesis.validator_registry).unwrap_or_default();
        hasher.update(b"validator_registry");
        hasher.update((rules.len() as u64).to_le_bytes());
        hasher.update(&rules);
    }

    let result = hasher.finalize();
    Hash::from_bytes(result.as_slice()).expect("SHA-256 always produces 32 bytes")
}

/// Calendar time one epoch spans: its block time, times the calendar scale.
/// The payout schedule counts its epochs per year in this time.
fn calendar_epoch_ms(time: &tenzro_consensus::TimeRules) -> u64 {
    time.checkpoint_interval_ms
        .saturating_mul(time.epoch_checkpoints)
        .saturating_mul(time.calendar_scale)
}

