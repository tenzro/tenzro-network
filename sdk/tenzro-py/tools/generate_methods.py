"""Generate ``tenzro/_methods.py`` from the node's method table.

The node classifies every JSON-RPC method it dispatches in
``crates/tenzro-node/src/rpc_gates.rs`` (``ADMIN_METHODS``, ``OWNER_METHODS``,
``OPEN_METHODS``). This script reads those tables and writes one typed method
per RPC method, for the synchronous and the asynchronous client. The test
suite regenerates the module in memory and refuses a stale copy.

    python tools/generate_methods.py          # rewrite tenzro/_methods.py
    python tools/generate_methods.py --check  # exit 1 when it is stale
"""

from __future__ import annotations

import keyword
import re
import sys
from pathlib import Path

PACKAGE = Path(__file__).resolve().parents[1]
REPO = PACKAGE.parents[1]
GATES = REPO / "crates" / "tenzro-node" / "src" / "rpc_gates.rs"
OUT = PACKAGE / "tenzro" / "_methods.py"

TABLES = (("ADMIN_METHODS", "admin"), ("OWNER_METHODS", "owner"), ("OPEN_METHODS", "open"))

ACCESS_DOC = {
    "admin": "Operator only: the node's access policy admits the operator DID or a policy admin.",
    "owner": "Needs the owner's proof (signature, passkey assertion or DPoP-bound token) in ``params``.",
    "open": "Open to any caller the node's access policy admits.",
}


def read_methods(source: str) -> dict[str, str]:
    """Every method name in the three tables, with its access class."""
    out: dict[str, str] = {}
    for table, access in TABLES:
        start = source.index(f"pub const {table}")
        body = source[start:]
        body = body[: body.index("];")]
        for line in body.splitlines()[1:]:
            code = line.split("//")[0]
            for name in re.findall(r'"([^"]+)"', code):
                if name in out:
                    raise SystemExit(f"{name} is in two access tables")
                out[name] = access
    if len(out) < 100:
        raise SystemExit("the rpc_gates tables were not found")
    return out


def snake(name: str) -> str:
    """The Python name of a method.

    ``tenzro_getBalance`` -> ``get_balance``; ``eth_getBalance`` ->
    ``eth_get_balance``; the Solana namespace (no prefix) -> ``solana_*``.
    """
    if "_" in name:
        prefix, verb = name.split("_", 1)
    else:
        prefix, verb = "solana", name
    words = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", verb)
    words = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", words).lower()
    py = words if prefix == "tenzro" else f"{prefix}_{words}"
    if keyword.iskeyword(py):
        py += "_"
    return py


HEADER = '''"""Every JSON-RPC method the node serves, one typed method each.

Generated by ``tools/generate_methods.py`` from the node's method table
(``crates/tenzro-node/src/rpc_gates.rs``). Do not edit by hand.
"""

from __future__ import annotations

from typing import Any, Literal

Access = Literal["admin", "owner", "open"]

Params = dict[str, Any] | list[Any] | None

'''


def render(methods: dict[str, str]) -> str:
    names = sorted(methods)
    py = {m: snake(m) for m in names}
    seen: dict[str, str] = {}
    for m, p in py.items():
        if p in seen:
            raise SystemExit(f"{m} and {seen[p]} both map to {p}")
        seen[p] = m
    lines = [HEADER]
    lines.append("#: Each method's access class on the node.")
    lines.append("METHODS: dict[str, Access] = {")
    for m in names:
        lines.append(f'    "{m}": "{methods[m]}",')
    lines.append("}")
    lines.append("")
    for cls, prefix, ret in (("Methods", "", "Any"), ("AsyncMethods", "async ", "Any")):
        lines.append("")
        kind = "asynchronous" if prefix else "synchronous"
        lines.append(f"class {cls}:")
        lines.append(f'    """The node\'s methods on the {kind} client. ``params`` goes to the method unchanged."""')
        lines.append("")
        lines.append(f"    {'async ' if prefix else ''}def call(self, method: str, params: Params = None) -> Any: ...")
        for m in names:
            lines.append("")
            lines.append(f"    {prefix}def {py[m]}(self, params: Params = None) -> {ret}:")
            lines.append(f'        """``{m}``. {ACCESS_DOC[methods[m]]}"""')
            await_ = "await " if prefix else ""
            lines.append(f'        return {await_}self.call("{m}", params)')
    return "\n".join(lines) + "\n"


def generate() -> str:
    return render(read_methods(GATES.read_text(encoding="utf-8")))


def main() -> int:
    text = generate()
    if "--check" in sys.argv[1:]:
        if OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is stale: run python tools/generate_methods.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
