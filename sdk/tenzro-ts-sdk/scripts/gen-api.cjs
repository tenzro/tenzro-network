'use strict';
// Generates API.md, the TypeScript SDK reference, from the source with the
// TypeScript compiler: every class and function the package exports, each
// public method's signature, its doc comment, @param, @returns, @throws and
// @example, and the RPC method it calls.
//
//   node scripts/gen-api.cjs           # write API.md
//   node scripts/gen-api.cjs --check   # exit 1 when API.md is stale
const ts = require('typescript');
const { readFileSync, writeFileSync, existsSync } = require('node:fs');
const { join } = require('node:path');

const root = join(__dirname, '..');
const entry = join(root, 'src', 'index.ts');
const config = ts.getParsedCommandLineOfConfigFile(join(root, 'tsconfig.json'), {}, {
  ...ts.sys,
  onUnRecoverableConfigFileDiagnostic: (d) => {
    throw new Error(ts.flattenDiagnosticMessageText(d.messageText, '\n'));
  },
});
// Read every package from its source, so each method's body (and the RPC
// method it calls) is in view, not only the built declarations.
const options = { ...config.options, baseUrl: root, paths: { '@tenzro/*': ['packages/*/src'] } };
const program = ts.createProgram([entry], options);
const checker = program.getTypeChecker();
const moduleSymbol = checker.getSymbolAtLocation(program.getSourceFile(entry));

const oneLine = (s) => s.replace(/\s+/g, ' ').trim();
const docText = (parts) => oneLine(ts.displayPartsToString(parts || []));
const esc = (s) => s.replace(/\|/g, '\\|');

function tags(symbol) {
  const out = { param: [], returns: '', throws: [], example: [] };
  for (const t of symbol.getJsDocTags(checker)) {
    const text = ts.displayPartsToString(t.text || []);
    if (t.name === 'param') {
      const m = text.match(/^(\S+)\s*-?\s*([\s\S]*)$/);
      if (m) out.param.push([m[1], oneLine(m[2])]);
    } else if (t.name === 'returns' || t.name === 'return') out.returns = oneLine(text);
    else if (t.name === 'throws') out.throws.push(oneLine(text));
    else if (t.name === 'example') out.example.push(text.trim());
  }
  return out;
}

function rpcMethods(decl) {
  const text = decl.getText();
  return [...new Set([...text.matchAll(/["']((?:tenzro|eth|net|web3)_[A-Za-z0-9]+)["']/g)].map((m) => m[1]))];
}

function renderFunctionLike(name, symbol, decl, out) {
  const sigs = checker.getTypeOfSymbolAtLocation(symbol, decl).getCallSignatures();
  out.push(`#### \`${name}\``, '');
  const doc = docText(symbol.getDocumentationComment(checker));
  if (doc) out.push(doc, '');
  for (const sig of sigs) {
    out.push('```ts', `${name}${checker.signatureToString(sig, decl, ts.TypeFormatFlags.NoTruncation)}`, '```', '');
  }
  const t = tags(symbol);
  const params = sigs[0] ? sigs[0].getParameters() : [];
  if (params.length) {
    out.push('| Param | Type | Description |', '|---|---|---|');
    for (const p of params) {
      const pd = p.valueDeclaration || decl;
      const ty = checker.typeToString(checker.getTypeOfSymbolAtLocation(p, pd), pd, ts.TypeFormatFlags.NoTruncation);
      const d = (t.param.find(([n]) => n === p.name) || [])[1] || '';
      out.push(`| \`${p.name}\` | \`${esc(oneLine(ty))}\` | ${esc(d)} |`);
    }
    out.push('');
  }
  if (sigs[0]) {
    const ret = checker.typeToString(sigs[0].getReturnType(), decl, ts.TypeFormatFlags.NoTruncation);
    out.push(`**Returns** \`${esc(oneLine(ret))}\`${t.returns ? ` ${t.returns}` : ''}`, '');
  }
  const rpc = rpcMethods(decl);
  if (rpc.length) out.push(`**Calls** ${rpc.map((m) => `[\`${m}\`](https://github.com/tenzro/tenzro-network/blob/main/docs/RPC.md#${m.toLowerCase()})`).join(', ')}`, '');
  out.push(`**Errors** ${t.throws.length ? t.throws.join('; ') : rpc.length ? 'Rejects with `RpcCallError` carrying the node\'s JSON-RPC error code and message.' : 'Throws on invalid input.'}`, '');
  if (t.example.length) for (const e of t.example) out.push(e.startsWith('```') ? e : '```ts\n' + e + '\n```', '');
}

const out = [
  '# tenzro-sdk API reference',
  '',
  '<!-- Generated by scripts/gen-api.cjs from the source. Do not edit by hand. -->',
  '',
  'Every class and function `tenzro-sdk` exports. Methods that call the node name the JSON-RPC method; its params, result and errors are in the [JSON-RPC reference](https://github.com/tenzro/tenzro-network/blob/main/docs/RPC.md).',
  '',
];
const exported = checker.getExportsOfModule(moduleSymbol).map((s) => (s.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(s) : s));
const classes = exported.filter((s) => s.flags & ts.SymbolFlags.Class).sort((a, b) => a.name.localeCompare(b.name));
const functions = exported.filter((s) => s.flags & ts.SymbolFlags.Function).sort((a, b) => a.name.localeCompare(b.name));
let methods = 0;
out.push('## Classes', '');
for (const cls of classes) {
  const decl = cls.valueDeclaration;
  if (!decl) continue;
  out.push(`### ${cls.name}`, '');
  const doc = docText(cls.getDocumentationComment(checker));
  if (doc) out.push(doc, '');
  const instance = checker.getDeclaredTypeOfSymbol(cls);
  const members = [
    ...checker.getPropertiesOfType(instance).map((m) => [m, '']),
    ...checker.getPropertiesOfType(checker.getTypeOfSymbolAtLocation(cls, decl)).filter((m) => m.name !== 'prototype').map((m) => [m, 'static ']),
  ];
  for (const [m, prefix] of members) {
    const md = m.valueDeclaration;
    if (!md || !(ts.isMethodDeclaration(md) || ts.isGetAccessorDeclaration(md))) continue;
    if (md.getSourceFile().isDeclarationFile) continue;
    const flags = ts.getCombinedModifierFlags(md);
    if (flags & (ts.ModifierFlags.Private | ts.ModifierFlags.Protected) || m.name.startsWith('#')) continue;
    if (ts.isGetAccessorDeclaration(md)) {
      const ty = checker.typeToString(checker.getTypeOfSymbolAtLocation(m, md), md, ts.TypeFormatFlags.NoTruncation);
      out.push(`#### \`${prefix}${m.name}\``, '', `Read-only \`${esc(oneLine(ty))}\`. ${docText(m.getDocumentationComment(checker))}`.trim(), '');
      continue;
    }
    renderFunctionLike(`${prefix}${m.name}`, m, md, out);
    methods++;
  }
}
out.push('## Functions', '');
for (const fn of functions) {
  const decl = fn.valueDeclaration || fn.declarations[0];
  if (decl.getSourceFile().isDeclarationFile) continue;
  renderFunctionLike(fn.name, fn, decl, out);
  methods++;
}
const text = out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
const target = join(root, 'API.md');
if (process.argv.includes('--check')) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== text) {
    console.error('API.md is stale: run node scripts/gen-api.cjs');
    process.exit(1);
  }
} else {
  writeFileSync(target, text);
  console.log(`wrote API.md: ${classes.length} classes, ${functions.length} functions, ${methods} methods and functions`);
}
